def face_words():
    rows = FACE.strip('\n').split('\n')
    assert len(rows) == 20 and all(len(r) == 20 for r in rows)
    return [sum(1 << (19 - y) for y in range(20) if rows[y][x] == '#') for x in range(20)]


def face_steps():
    """The steps of the marker REM ==== FACE: each column word into R99 (SINT), AGRAPH at x R30, row R31."""
    out = []
    for w in face_words():
        out += [str(w), 'SINT', 'STO 99', 'DROP', 'RCL 31', 'RCL 30', 'AGRAPH 99', 'STO 30']
    return out


def bitmap(t):
    rows = [r for r in PIECES[t].strip('\n').split('\n')]
    assert len(rows) == GH and all(len(r) == GW for r in rows), t
    return {(x, y) for y, r in enumerate(rows) for x, ch in enumerate(r) if ch == '#'}   # y 0 = the top row


def shapes(t):
    S = bitmap(t)
    O = {(x, y) for x, y in S if not all(n in S for n in ((x - 1, y), (x + 1, y), (x, y - 1), (x, y + 1)))}
    M = {(x + dx, y + dy) for x, y in S for dx in (-1, 0, 1) for dy in (-1, 0, 1)}
    return O, S, M


def words(cells):
    """The 24 column words of a square for a set of glyph cells (x 0-17, y 0-19 from the top)."""
    out = [0] * SQ
    for x, y in cells:
        out[GX + x] |= 1 << (GY + GH - 1 - y)
    return out


DITHER = (0x555555, 0xAAAAAA)          # the columns j = 1, 3, ... and j = 2, 4, ...
FULL, EDGE = (1 << SQ) - 1, 3 | 3 << (SQ - 2)


def square_words(p, dark):
    """The 24 words drawn for piece p (-6 .. 6) on a light or dark square."""
    if p == 0:
        g, m = [0] * SQ, [0] * SQ
    else:
        O, S, M = (words(c) for c in shapes(abs(p)))
        g, m = (O if p > 0 else S), M
    if not dark:
        return g
    return [(DITHER[j % 2] & ~m[j] & FULL) | g[j] for j in range(SQ)]


def glyph_steps():
    """The steps of the marker REM ==== GLYPHS: the words O, S, M of each piece into the matrix GL (INDEX "GL" set):
    row 7 + t the outline O (a white piece), row 7 - t the silhouette S (a black piece), row 26 + t the mask M; only the
    columns 4-21 (STOIJ to column 4, then 18 STOSEQ)."""
    out = []
    for t in range(1, 7):
        for row, w in zip((7 + t, 7 - t, 26 + t), (words(c) for c in shapes(t))):
            out += [str(row), '4', 'STOIJ', 'DROP', 'DROP']
            for v in w[GX:GX + GW]:
                out += [str(v), 'STOSEQ', 'DROP']
    return out


def mock(board):
    """The pixels of the board for a position (board[s] as chess47ref.Pos.bd), as the program draws it."""
    pix = set()
    for r in range(8):
        for f in range(8):
            s = 10 * (r + 2) + f + 2
            ws = square_words(board[s], (f + r) % 2 == 0)
            for j, w in enumerate(ws):
                for i in range(SQ):
                    if w >> i & 1:
                        pix.add((BX + SQ * f + j, BY + SQ * r + i))
    return pix


